      chassisGLTF.materials.glossy.needsUpdate = true;
      chassisGLTF.materials.displaymat.needsUpdate = true;
      chassisGLTF.materials.chassisglowmat.needsUpdate = true;
      chassisGLTF.materials.seatsmat.needsUpdate = true;

